import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {selectProfessional,resolveSourceV2} from '../scripts/provider-v2.mjs';
import {repositoryRoot,loadCatalogue,containedPath,resolveSelection,lookup} from '../scripts/learning-cli.mjs';
const cat=loadCatalogue();
assert.deepEqual(selectProfessional().assets,[]);
const ids=cat.assets.slice(0,4).map(a=>a.id);
const defaults=selectProfessional({ids},repositoryRoot);
assert.deepEqual(defaults.assets,[],'Naming candidates alone must not load them');
assert.equal(defaults.candidate_policy,'excluded_by_default');
assert.ok(selectProfessional({roles:['NUM'],query:'资源'},repositoryRoot).assets.every(a=>a.default_use===true),'Only normally enabled items may bypass candidate exclusion');
const result=selectProfessional({ids,includeCandidates:true},repositoryRoot,{maxAssets:2,maxCharacters:20000});
assert.equal(result.candidate_policy,'explicit_opt_in');
assert.equal(result.assets.length,2);assert.equal(result.status,'partial');assert.equal(result.not_loaded.length,2);assert.equal(result.sources_read,false);
const requestedOrder=['PRO-GP-001-mechanic-cross-context-greybox','expert-GP'];
assert.equal(selectProfessional({ids:requestedOrder,includeCandidates:true},repositoryRoot,{maxAssets:1}).assets[0].id,requestedOrder[0],'The reading cap must respect explicit ID priority');
assert.deepEqual(selectProfessional({ids:[...requestedOrder,requestedOrder[0]],includeCandidates:true},repositoryRoot).assets.map(a=>a.id),requestedOrder,'Repeated IDs must not duplicate reading or consume its budget');
assert.equal(selectProfessional({roles:['NUM'],query:'分层平衡矩阵审查',includeCandidates:true},repositoryRoot,{maxAssets:1}).assets[0].id,'balance-matrix-review','A specific topic must precede broad role fallback under the cap');
assert.equal(selectProfessional({ids:['balance-matrix-review']},repositoryRoot,{maxAssets:1}).assets.length,0,'Ranking must not enable unapproved candidates');
assert.doesNotThrow(()=>selectProfessional({},repositoryRoot,{maxAssets:33}),'Reading budgets must not be pinned to the original catalogue size');
assert.throws(()=>selectProfessional({},repositoryRoot,{maxAssets:101}),/budget/);
for(const asset of result.assets){
 assert.equal(asset.content,fs.readFileSync(containedPath(repositoryRoot,asset.path),'utf8'));
 assert.equal(asset.sha256,crypto.createHash('sha256').update(asset.content).digest('hex'));
 assert.equal(asset.sole_basis_for_important_decision,false);
}
assert.throws(()=>selectProfessional({ids:['PRO-PM-002-automation-production-boundary-audit']}),/retired/);
assert.throws(()=>selectProfessional({unrecognized:true}),/Unknown/);
assert.throws(()=>selectProfessional({},repositoryRoot,{maxAssets:0}),/budget/);
const enabled=selectProfessional({ids:['causal-system-map','PRO-UX-001-state-input-feedback-recovery-audit']},repositoryRoot);
assert.equal(enabled.assets.length,2,'Both user-directed items are usable without candidate flags or context tags');
assert.equal(enabled.candidate_policy,'default_use_enabled');
assert.equal(enabled.default_use_ids.length,2);
assert.ok(enabled.assets.every(a=>a.sole_basis_for_important_decision===false));
const request={ids:['causal-system-map','balance-matrix-review']};
assert.deepEqual(resolveSelection(request).items.filter(a=>a.available).map(a=>a.id),lookup(request).map(a=>a.id));
assert.deepEqual(selectProfessional(request).usage.map(a=>[a.id,a.status]),[['causal-system-map','normal'],['balance-matrix-review','trial']]);
assert.deepEqual(selectProfessional(request).assets.map(a=>a.id),lookup(request).map(a=>a.id));
const problems=JSON.parse(fs.readFileSync(containedPath(repositoryRoot,'agents/problem-routes.json'),'utf8')).routes;
for(const problem of problems){
 const routed=selectProfessional({problem:problem.id,includeCandidates:true},repositoryRoot,{maxAssets:1});
 assert.equal(routed.problem,problem.id);assert.equal(routed.assets[0].id,problem.ids[0]);assert.ok(routed.operation.length>0);
 assert.equal(selectProfessional({query:problem.aliases[0],includeCandidates:true},repositoryRoot,{maxAssets:1}).assets[0].id,problem.ids[0]);
}
assert.equal(selectProfessional({problem:'growth-pacing',ids:['expert-GP'],includeCandidates:true},repositoryRoot,{maxAssets:1}).assets[0].id,'expert-GP','Explicit IDs retain precedence over route suggestions');
assert.throws(()=>selectProfessional({problem:'missing-route'}),/Unknown/);
assert.ok(selectProfessional({problem:'mechanic-value'}).assets.every(a=>a.use_status==='normal'),'A problem route cannot auto-enable trial items');
const low=selectProfessional({ids,includeCandidates:true},repositoryRoot,{maxCharacters:100,maxAssets:2});
assert.equal(low.assets.length,0);assert.equal(low.status,'partial');
assert.equal(resolveSourceV2('knowledge:domain:missing',containedPath(repositoryRoot,'tests')).status,'unavailable');
console.log('PASS: actual v2 professional content selection, no blanket loading, source plan disclosure, file hashes, reading caps, retired and unknown field rejection.');
